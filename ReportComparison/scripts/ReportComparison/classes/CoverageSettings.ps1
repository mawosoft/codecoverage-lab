using namespace System
using namespace System.Collections
using namespace System.Xml.Linq

<#
    coverlet and mscc handle 'IncludeTestAssembly' differently.
    - coverlet: If true, the test assembly is removed from possible candidates **before** filtering.
      An Include filter cannot add it back again. It also excludes it from instrumentation.
    - MSCC: This is pure result filter that is applied **after** instrumentation and collection already
      have taken place. Only the Include/Exclude filters control instrumentation.
    To get the same behavior from both, we always have 'IncludeTestAssembly=true' and we use an explicit
    Exclude filter to exclude the test assembly from everything by default. That filter can be removed
    by setting 'DontExcludeTestAssembly' on the class instance.
#>
class CoverageSettings {
    [string]$Format
    [bool]$SingleHit
    [bool]$StaticInstrumentation
    [bool]$DontExcludeTestAssembly

    static [CoverageSettings]Create([string]$family) {
        if ($family -eq 'coverlet') {
            return [CoverletCoverageSettings]::new()
        }
        elseif ($family -eq 'mscc') {
            return [MsccCoverageSettings]::new()
        }
        else {
            throw [ArgumentException]::new([NullString]::Value, 'family')
        }
    }

    [string]GetFriendlyName() { throw [NotImplementedException]::new() }
    [IDictionary]ToDictionary() { throw [NotImplementedException]::new() }
    [IDictionary]ToTestConfig() { throw [NotImplementedException]::new() }
    # TODO return empty by default?
    [array]ToToolArguments() { throw [NotImplementedException]::new() }
    [array]ToMsbuildPropertyArguments() { throw [NotImplementedException]::new() }

    [XElement]ToRunSettings() {
        return [XElement]::new(
            [XName]'RunSettings',
            [XElement]::new(
                [XName]'RunConfiguration',
                [XElement]::new([XName]'SkipDefaultAdapters', $true)
            ),
            [XElement]::new(
                [XName]'DataCollectionRunSettings',
                [XElement]::new(
                    [XName]'DataCollectors',
                    [XElement]::new(
                        [XName]'DataCollector',
                        [XAttribute]::new([XName]'friendlyName', $this.GetFriendlyName()),
                        $this.ToConfiguration()
                    )
                )
            )
        )
    }

    [XElement]ToConfiguration() {
        $cfg = [XElement]::new([XName]'Configuration')
        $this.BuildXml($cfg, $this.ToDictionary())
        return $cfg
    }

    hidden [void]BuildXml([XElement]$parent, [Object]$data) {
        if ($data -is [IDictionary]) {
            foreach ($kvp in $data.GetEnumerator()) {
                $e = [XElement]::new([XName]$kvp.Name)
                $parent.Add($e)
                $this.BuildXml($e, $kvp.Value)
            }
        }
        elseif ($data -is [array]) {
            if ($null -eq $parent.Parent) { throw [InvalidOperationException]::new() }
            $n = [string]$parent.Parent.Name
            if ($n[-1] -ceq 's') {
                $name = [XName]$n.Substring(0, $n.Length - 1)
            }
            else {
                $name = $parent.Name
                $parent = $parent.Parent
                $parent.RemoveNodes()
            }
            foreach ($item in $data) {
                $e = [XElement]::new($name)
                $parent.Add($e)
                $this.BuildXml($e, $item)
            }
        }
        else {
            $parent.Add($data)
        }
    }
}

class CoverletCoverageSettings : CoverageSettings {

    [string]GetFriendlyName() { return 'XPlat Code Coverage' }

    [IDictionary]ToDictionary() {
        $settings = [ordered]@{
            Format                 = 'cobertura'
            IncludeTestAssembly    = $true
            SkipAutoProps          = $false
            SingleHit              = $false
            Include                = '[CoverageDemo]*,[CoverageDemo.Tests]*'
            Exclude                = '[CoverageDemo.Tests]*'
            ExcludeByAttribute     = 'GeneratedCodeAttribute,ExcludeFromCodeCoverageAttribute,TestSDKAutoGeneratedCode'
            DoesNotReturnAttribute = 'DoesNotReturnAttribute'
        }
        if (-not $this.Format) { $settings.Remove('Format') }
        $settings['SingleHit'] = $this.SingleHit
        if ($this.DontExcludeTestAssembly) { $settings.Remove('Exclude') }
        return $settings
    }

    [IDictionary]ToTestConfig() {
        return @{
            platformOptions = @{
                Coverlet = $this.ToDictionary()
            }
        }
    }

    [array]ToToolArguments() {
        $result = [ArrayList]::new()
        $kebab = [Text.Json.JsonNamingPolicy]::KebabCaseLower
        $settings = $this.ToDictionary()
        foreach ($kvp in $settings.GetEnumerator()) {
            $option = '--' + $kebab.ConvertName($kvp.Key)
            if ($kvp.Value -is [bool]) {
                if ($kvp.Value) { $result.Add($option) }
            }
            elseif ($kvp.Value -is [string]) {
                foreach ($item in $kvp.Value.Split([char]',')) {
                    $result.Add($option)
                    $result.Add($item)
                }
            }
            else {
                throw [InvalidCastException]::new()
            }
        }
        return $result
    }

    [array]ToMsbuildPropertyArguments() { 
        $result = [ArrayList]::new()
        $result.Add('-p:CollectCoverage=true')
        # Also needs -p:CoverletOutput=file or -p:CoverletOutput=dir/
        $settings = $this.ToDictionary()
        foreach ($kvp in $settings.GetEnumerator()) {
            $name = $kvp.Key
            if ($name -eq 'Format') { $name = 'CoverletOutputFormat' }
            if ($kvp.Value -is [bool]) {
                $result.Add("-p:$name=$($kvp.Value ? 'true' : 'false' )")
            }
            elseif ($kvp.Value -is [string]) {
                $result.Add("-p:$name=`"$($kvp.Value)`"")
            }
            else {
                throw [InvalidCastException]::new()
            }
        }
        return $result
    }
}

class MsccCoverageSettings : CoverageSettings {

    [string]GetFriendlyName() { return 'Code Coverage' }

    [IDictionary]ToDictionary() {
        $settings = [ordered]@{
            Format                 = 'xml'
            IncludeTestAssembly    = $true
            DoesNotReturnAttribute = 'AllAssemblies'
            CodeCoverage           = [ordered]@{
                ModulePaths                         = [ordered]@{
                    Include = @('.*CoverageDemo\.dll$', '.*CoverageDemo\.Tests\.dll$')
                    Exclude = @('.*CoverageDemo\.Tests\.dll$')
                }
                Attributes                          = [ordered]@{
                    Exclude = @(
                        '^System\.CodeDom\.Compiler\.GeneratedCodeAttribute$'
                        '^System\.Diagnostics\.CodeAnalysis\.ExcludeFromCodeCoverageAttribute$'
                        '^Microsoft\.VisualStudio\.TestPlatform\.TestSDKAutoGeneratedCode$'
                    )
                }
                SkipAutoProperties                  = $false
                EnableDynamicNativeInstrumentation  = $false
                EnableStaticNativeInstrumentation   = $false
                EnableDynamicManagedInstrumentation = $true
                EnableStaticManagedInstrumentation  = $false
            }
        }
        if (-not $this.Format) { $settings.Remove('Format') }
        $cc = $settings['CodeCoverage']
        if ($this.StaticInstrumentation) {
            $cc['EnableDynamicManagedInstrumentation'] = $false
            $cc['EnableStaticManagedInstrumentation'] = $true
        }
        if ($this.DontExcludeTestAssembly) { $cc['ModulePaths'].Remove('Exclude') }
        return $settings
    }

    [IDictionary]ToTestConfig() {
        return @{
            codeCoverage = $this.ToDictionary()
        }
    }
}
